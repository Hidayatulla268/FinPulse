// Generates ISO date relative to anchor date for deterministic SSR builds
function relativeDate(daysAgo: number): string {
  const d = new Date('2026-10-22T11:00:00+05:30');
  d.setDate(d.getDate() - daysAgo);
  return d.toISOString().split('T')[0];
}

